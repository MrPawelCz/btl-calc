const LANGUAGES = Object.keys(I18N);
const DEFAULT_LANGUAGE = 'en';
const LANGUAGE_KEY = 'btlcalc:lang';
let currentLanguage = DEFAULT_LANGUAGE;

// t('key', { name: value }) fills {name} placeholders; unknown keys fall back to English.
function t(key, params) {
  const text = I18N[currentLanguage][key] ?? I18N[DEFAULT_LANGUAGE][key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? params[name] : match));
}

function loadLanguage() {
  try {
    const saved = localStorage.getItem(LANGUAGE_KEY);
    if (LANGUAGES.includes(saved)) currentLanguage = saved;
  } catch (e) {}
}
